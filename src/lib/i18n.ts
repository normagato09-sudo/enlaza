const dicts: Record<Lang, Dict> = { es, en };

export function useLang() {
  const lang = useStored<Lang>("enlaza-lang", "es");
  return {
    lang,
    t: dicts[lang] ?? es,
    setLang: (l: Lang) => {
      writeStored("enlaza-lang", l);
      document.documentElement.lang = l;
    },
  };
}
